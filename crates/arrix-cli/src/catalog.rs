//! `docs/CONFIG-CATALOG.md`: everything there is to configure, as a
//! reference doc generated from the registry and the specs (ADR-0016,
//! constraint 3). A test holds it fresh; `UPDATE_SNAPSHOTS=1` regenerates it.

use std::fmt::Write as _;

use arrix_config::{BUILTIN_THEMES, CONTEXTS, CommandRegistry, SETTINGS, THEME_ROLES};
use arrix_plugin_api::FeatureTypeSpec;

pub fn run() -> std::process::ExitCode {
    use std::io::Write as _;
    let types = crate::plugins::feature_types(&crate::plugins::registry());
    let text = render(&CommandRegistry::new(&types), &types);
    if write!(std::io::stdout(), "{text}").is_err() {
        return std::process::ExitCode::from(2);
    }
    std::process::ExitCode::SUCCESS
}

/// The catalog's text for the compiled-in plugins' `types`.
pub fn render(commands: &CommandRegistry, types: &[FeatureTypeSpec]) -> String {
    let mut out = String::from(
        "# Configuration catalog\n\n\
         Generated by `arrix config catalog` (`UPDATE_SNAPSHOTS=1 cargo test -p arrix-cli catalog`), from\n\
         the command registry and the setting specs; a test holds it fresh. Do not edit.\n\
         `arrix describe --json` gives the same, with the effective values, and\n\
         `arrix config schema` the files' JSON Schemas.\n\n",
    );
    out.push_str("## Settings (`settings.toml`)\n\n| Id | Default | What |\n|---|---|---|\n");
    for s in SETTINGS {
        let default = serde_json::to_string(&s.default.value()).expect("plain data");
        let _ = writeln!(out, "| `{}` | `{default}` | {} |", s.id, s.doc);
    }
    out.push_str(
        "\n## Commands\n\n| Id | Title | Default keys | When | Ribbon |\n|---|---|---|---|---|\n",
    );
    for c in &commands.commands {
        let keys = c.keys.join(", ");
        let ribbon = c
            .ribbon
            .as_ref()
            .map_or(String::new(), |r| format!("{} / {}", r.tab, r.group));
        let _ = writeln!(
            out,
            "| `{}` | {} | {keys} | {} | {ribbon} |",
            c.id,
            c.title,
            c.when.as_deref().unwrap_or("")
        );
    }
    out.push_str("\n## Ribbon tabs (`ui.ribbon.hidden-tabs`)\n\n");
    for t in &commands.tabs {
        let _ = writeln!(out, "- `{}`: {}", t.id, t.title);
    }
    out.push_str("\n## Keymap contexts (`when`)\n\n");
    for (name, doc) in CONTEXTS {
        let _ = writeln!(out, "- `{name}`: {doc}");
    }
    let _ = writeln!(
        out,
        "\n## Theme roles (`themes/<name>.toml`)\n\nBuilt-in themes: {}.\n\n| Role | What |\n|---|---|",
        BUILTIN_THEMES
            .iter()
            .map(|t| format!("`{t}`"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    for (role, doc) in THEME_ROLES {
        let _ = writeln!(out, "| `{role}` | {doc} |");
    }
    out.push_str("\n## Feature types (`[defaults.\"<type>\"]`)\n");
    for ty in types {
        let _ = writeln!(out, "\n### `{}`: {}\n", ty.id, ty.title);
        if ty.params.is_empty() {
            out.push_str("No parameters.\n");
            continue;
        }
        out.push_str("| Parameter | Kind | Built-in default |\n|---|---|---|\n");
        for p in &ty.params {
            let _ = writeln!(out, "| `{}` | {:?} | `{}` |", p.name, p.kind, p.default);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use crate::plugins;

    #[test]
    fn the_catalog_is_fresh() {
        let types = plugins::feature_types(&plugins::registry());
        let text = super::render(&arrix_config::CommandRegistry::new(&types), &types);
        let path =
            std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../docs/CONFIG-CATALOG.md");
        if std::env::var_os("UPDATE_SNAPSHOTS").is_some() {
            std::fs::write(&path, &text).expect("write the catalog");
            return;
        }
        let have = std::fs::read_to_string(&path).expect("read docs/CONFIG-CATALOG.md");
        assert!(
            have == text,
            "docs/CONFIG-CATALOG.md is stale: rerun `UPDATE_SNAPSHOTS=1 cargo test -p arrix-cli catalog`"
        );
    }
}
